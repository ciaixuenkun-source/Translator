  benchmarkFreeServices: (payload) => ipcRenderer.invoke("benchmark-free-translation-services", payload),
  openServiceSettings: (payload) => ipcRenderer.send("open-service-settings", payload),
  getLanguagePreferences: () => ipcRenderer.invoke("language-preferences-bootstrap"),
