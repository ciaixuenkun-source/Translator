  saveSceneTranslationMethod: (payload) => ipcRenderer.invoke("save-scene-translation-method", payload),
  saveGameFullscreenDuration: (value) => ipcRenderer.invoke("save-game-fullscreen-duration", value),
  getOverlayStyles: () => ipcRenderer.invoke("overlay-style-settings-bootstrap"),
  saveOverlayStyles: (payload) => ipcRenderer.invoke("save-overlay-style-settings", payload),
  updateOverlayPreview: (payload) => ipcRenderer.send("update-overlay-style-preview", payload),
  closeOverlayPreview: () => ipcRenderer.send("close-overlay-style-preview"),
  testTranslator: (payload) => ipcRenderer.invoke("test-translator-settings", payload),
